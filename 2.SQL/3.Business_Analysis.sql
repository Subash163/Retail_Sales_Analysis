    CASE
        WHEN Discount = 0
            THEN 'No Discount'
        WHEN Discount <= 0.20
            THEN 'Low Discount'
        WHEN Discount <= 0.50
            THEN 'Medium Discount'
        ELSE 'High Discount'
    END
