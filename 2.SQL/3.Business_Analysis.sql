/* ---------------------------------------------------------
   Q46. Rank products by total sales.
   --------------------------------------------------------- */
WITH ProductSales AS (
    SELECT
        p.Product_ID,
        p.Product_name,
        ROUND(SUM(s.Sales), 2) AS Total_Sales
    FROM sales s
    INNER JOIN products p
        ON s.Product_ID = p.Product_ID
    GROUP BY
        p.Product_ID,
        p.Product_name
)
SELECT
    Product_ID,
    Product_name,
    Total_Sales,
    RANK() OVER (
        ORDER BY Total_Sales DESC
    ) AS Sales_Rank
FROM ProductSales
ORDER BY Sales_Rank;

