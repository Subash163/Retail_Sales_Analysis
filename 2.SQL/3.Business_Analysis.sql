/* ---------------------------------------------------------
   Q48. Find the top 3 products within each category
        based on sales.
   --------------------------------------------------------- */
WITH ProductSales AS (
    SELECT
        p.Category,
        p.Product_ID,
        p.Product_name,
        SUM(s.Sales) AS Total_Sales
    FROM sales s
    INNER JOIN products p
        ON s.Product_ID = p.Product_ID
    GROUP BY
        p.Category,
        p.Product_ID,
        p.Product_name
),
RankedProducts AS (
    SELECT
        Category,
        Product_ID,
        Product_name,
        ROUND(Total_Sales, 2) AS Total_Sales,
        ROW_NUMBER() OVER (
            PARTITION BY Category
            ORDER BY Total_Sales DESC
        ) AS Product_Rank
    FROM ProductSales
)
SELECT *
FROM RankedProducts
WHERE Product_Rank <= 3
ORDER BY
    Category,
    Product_Rank;

