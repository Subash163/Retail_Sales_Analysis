/* ---------------------------------------------------------
   Q58. Which categories should management prioritize
        based on sales and profit?
   --------------------------------------------------------- */
SELECT
    p.Category,
    ROUND(SUM(s.Sales), 2) AS Total_Sales,
    ROUND(SUM(s.Profit), 2) AS Total_Profit,
    ROUND(
        SUM(s.Profit) /
        NULLIF(SUM(s.Sales), 0) * 100,
        2
    ) AS Profit_Margin,
    CASE
        WHEN SUM(s.Profit) > 0
             AND SUM(s.Sales) > 10000
            THEN 'High Priority'
        WHEN SUM(s.Profit) > 0
            THEN 'Maintain'
        ELSE 'Review'
    END AS Business_Action
FROM sales s
INNER JOIN products p
    ON s.Product_ID = p.Product_ID
GROUP BY p.Category
ORDER BY Total_Sales DESC;

/* ---------------------------------------------------------
   Q59. Identify products requiring management review.
   --------------------------------------------------------- */
SELECT
    p.Product_ID,
    p.Product_name,
    p.Category,
    ROUND(SUM(s.Sales), 2) AS Total_Sales,
    ROUND(SUM(s.Profit), 2) AS Total_Profit,
    ROUND(
        SUM(s.Profit) /
        NULLIF(SUM(s.Sales), 0) * 100,
        2
    ) AS Profit_Margin,
    CASE
        WHEN SUM(s.Profit) < 0
            THEN 'Loss Making'
        WHEN SUM(s.Profit) /
             NULLIF(SUM(s.Sales), 0) < 0.05
            THEN 'Low Margin'
        ELSE 'Healthy'
    END AS Product_Status
FROM sales s
INNER JOIN products p
    ON s.Product_ID = p.Product_ID
GROUP BY
    p.Product_ID,
    p.Product_name,
    p.Category
ORDER BY Total_Profit ASC;

